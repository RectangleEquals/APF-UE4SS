class APFrameworkWorld(World):
    """
    AP Framework World - A template for games using the AP Framework mod system.

    This world reads item and location definitions from a capabilities config
    embedded as base64 in the YAML, allowing any game with AP Framework
    mods to be randomized in Archipelago.
    """

    # =========================================================================
    # Class Variables - Override these in game-specific subclasses
    # =========================================================================

    game: ClassVar[str] = "APFramework"  # Change to your game's name
    web: ClassVar[WebWorld] = APFrameworkWebWorld()

    options_dataclass = APFrameworkOptions
    options: APFrameworkOptions

    # Topology: 0 = no logic, 1 = basic, 2 = advanced
    topology_present: ClassVar[bool] = False

    # =========================================================================
    # Instance Variables
    # =========================================================================

    item_table: Dict[str, ItemData]
    location_table: Dict[str, LocationData]
    region_table: Dict[str, str]  # region_name -> logic expression string
    capabilities: Dict[str, Any]
    id_remapping: Dict[int, int]
    log: APFLogger

    # Item/Location name to ID mappings (required by Archipelago)
    item_name_to_id: ClassVar[Dict[str, int]] = {}
    location_name_to_id: ClassVar[Dict[str, int]] = {}

    # Canonical union ID mapping — built once per multiworld generation.
    # Populated by _build_canonical_ids() on the first APF player's generate_early().
    # Subsequent players' generate_early() calls skip the build (flag already set).
    _canonical_built: ClassVar[bool] = False
    _canonical_multiworld_seed: ClassVar[Optional[int]] = None
    _canonical_player_remaps: ClassVar[Dict[int, Dict[int, int]]] = {}

    # =========================================================================
    # Initialization
    # =========================================================================

    def __init__(self, multiworld: MultiWorld, player: int):
        super().__init__(multiworld, player)
        self.item_table = {}
        self.location_table = {}
        self.region_table = {}
        self.capabilities = {}
        self.id_remapping = {}
        self.log = APFLogger()  # default warn level until generate_early

    # =========================================================================
    # World Generation
    # =========================================================================

    def generate_early(self) -> None:
        """
        Decode base64 capabilities data and set up item/location tables.
        Called before item/location creation.
        """
        # Initialize logger from YAML options
        log_level = getattr(self.options, "apf_log", None)
        log_file = getattr(self.options, "apf_logfile", None)
        self.log = APFLogger(
            min_level=log_level.current_key if log_level else "warn",
            logfile=log_file.value if log_file else "",
        )

        # Build canonical union ID mapping across all APF players (runs once per multiworld).
        # Sets class-level item_name_to_id / location_name_to_id with the full union of all
        # players' items/locations. Must run before per-player tables are built so that
        # subsequent generate_early() calls do not overwrite the union with a subset.
        self._build_canonical_ids()

        cap_data = self.options.capabilities_data.value
        if not cap_data:
            self.log.warn(
                f"[{self.game}] *** STUB MODE — no capabilities_data provided. ***\n"
                "This world contains placeholder content only and is not suitable for "
                "real gameplay. Real usage requires capabilities_data in the player YAML."
            )
            self._is_stub = True
            self.capabilities = self._process_capabilities(json.loads(_STUB_CAPABILITIES_JSON))
        else:
            self._is_stub = False
            try:
                decoded = base64.b64decode(cap_data).decode("utf-8")
                self.capabilities = self._process_capabilities(json.loads(decoded))
            except Exception as e:
                raise Exception(f"[{self.game}] Failed to decode capabilities_data: {e}")

        # Filter capabilities by logic (option-gated entries pruned if always-false)
        self._filter_by_logic()

        # Apply item overrides (cross-mod item type changes)
        self._apply_item_overrides()

        # Build region table first so location derivation can use known_regions
        self.region_table = self._build_region_table()

        # Build item and location tables
        self.item_table = build_item_table(self.capabilities)
        known_regions = set(self.region_table.keys()) if self.region_table else None
        self.location_table = build_location_table(self.capabilities, known_regions)

        # Resolve item amount expressions (must run after location_table is built for % forms)
        self._resolve_item_amounts(self._build_option_values())

        # Validate {option_key} references in Item count expressions.
        # Must run after item_table and location_table are built (needed for softlock check).
        # Raises ValueError on type mismatch or unknown key; warns on Toggle use or softlock risk.
        from . import Rules as _Rules
        _Rules.validate_item_count_options(self)

        # Apply this player's canonical remap to local item/location tables.
        # Must run BEFORE the hints loop below — the local/early hints read
        # item_table[name].code and add it to multiworld.local_items[player].
        # Using canonical codes here ensures local_items matches Item.code values
        # created in create_items() (which also uses canonical IDs via item_name_to_id).
        player_remap = type(self)._canonical_player_remaps.get(self.player, {})
        if player_remap:
            self.item_table = {
                n: d._replace(code=player_remap.get(d.code, d.code))
                for n, d in self.item_table.items()
            }
            self.location_table = {
                n: d._replace(code=player_remap.get(d.code, d.code))
                for n, d in self.location_table.items()
            }
        self.id_remapping = player_remap  # {} for same-mod players; used by fill_slot_data()

        # Set topology_present based on logic mode
        if self.options.logic_mode.value == 1 and self.region_table:  # basic
            self.__class__.topology_present = True

        # Apply placement hints from capabilities
        # Hints are generation-time only — independent of logic (which controls access rules).
        option_values = self._build_option_values()
        seen_early: set = set()

        for item_entry in self.capabilities.get("items", []):
            name = item_entry.get("name", "")
            if name not in self.item_table:
                continue

            # start — push one copy to start inventory; reduce pool count by 1
            if self._hint_active(item_entry.get("start", ""), option_values):
                self.multiworld.push_precollected(self.create_item(name))
                old = self.item_table[name]
                if old.count > 0:
                    self.item_table[name] = old._replace(count=old.count - 1)

            # early — request one copy in sphere 1 (best-effort, de-duplicated per name)
            if self._hint_active(item_entry.get("early", ""), option_values) \
                    and name not in seen_early:
                seen_early.add(name)
                typ = item_entry.get("type", "filler")
                if typ in ("filler", "trap"):
                    self.log.warn(
                        f"Item '{name}' has 'early' hint but is '{typ}' — early filler is unusual",
                        "Placement",
                    )
                self.multiworld.local_early_items[self.player][name] = (
                    self.multiworld.local_early_items[self.player].get(name, 0) + 1
                )

            # local — must stay in this player's world
            if self._hint_active(item_entry.get("local", ""), option_values):
                item_id = self.item_table[name].code
                if item_id is not None:
                    self.multiworld.local_items[self.player].add(item_id)

        for loc_entry in self.capabilities.get("locations", []):
            loc_name = loc_entry.get("name", "")
            prio_active = self._hint_active(loc_entry.get("priority", ""), option_values)
            excl_active = self._hint_active(loc_entry.get("exclude", ""), option_values)
            if prio_active and excl_active:
                self.log.warn(
                    f"Location '{loc_name}' has both 'priority' and 'exclude' hints — "
                    f"priority wins",
                    "Placement",
                )
            if prio_active:
                self.options.priority_locations.value.add(loc_name)
            elif excl_active:
                self.options.exclude_locations.value.add(loc_name)

        # Check for ID conflicts with other worlds
        self.check_id_conflicts()

        # Update reverse mappings and network data package.
        # Archipelago snapshots the data package at module import time (when our
        # ClassVars are still {}). We must refresh it after populating the tables.
        self._update_data_package()

        # Statistics summary
        logic_str = "basic" if self.options.logic_mode.value == 1 else "none"
        self.log.info(
            f"generate_early complete: {len(self.item_table)} items, "
            f"{len(self.location_table)} locations, "
            f"{len(self.region_table)} regions, "
            f"logic_mode={logic_str}",
            "World",
        )
        goals = self.capabilities.get("goals", [])
        overrides = self.capabilities.get("item_overrides", [])
        if goals or overrides:
            self.log.info(
                f"  {len(goals)} goals, {len(overrides)} item overrides",
                "World",
            )

        # Validate (Checked: X) location names in goal logic
        from .LogicParser import parse as _lp_parse
        for goal in goals:
            goal_logic = goal.get("logic", "")
            if not goal_logic or "(Checked:" not in goal_logic:
                continue
            try:
                ast = _lp_parse(goal_logic)
                for cn in _collect_checked_nodes(ast):
                    if cn.location not in self.location_table:
                        self.log.error(
                            f"Goal '{goal.get('name', '?')}' references "
                            f"'(Checked: {cn.location})' but no location named "
                            f"'{cn.location}' exists in the location pool. "
                            f"This goal will be permanently incompletable.",
                            "World",
                        )
            except Exception:
                pass  # Parse errors will surface elsewhere

    def _hint_active(self, hint_val, option_values: dict) -> bool:
        """Return True if a placement hint is currently active.

        hint_val may be: True/False (Python bool, from JSON bool true/false),
        "" or None (absent / disabled), or a logic expression string.
        Logic expressions use only (Option:) nodes — (Item:) and (Can Access:)
        are invalid in hint context and evaluate as False (hint inactive).
        """
        if isinstance(hint_val, bool):
            return hint_val
        if not hint_val:   # None or ""
            return False
        # Logic expression — active unless it always evaluates to False
        return not is_always_false(str(hint_val), option_values)

    def _process_capabilities(self, data: dict) -> dict:
        """Unwrap nested structure and validate."""
        # The C++ framework nests locations/items/regions/goals/item_overrides
        # under a "capabilities" key
        if "capabilities" in data and isinstance(data["capabilities"], dict):
            caps = data["capabilities"]
            if "regions" in caps:
                data["regions"] = caps["regions"]
            if "locations" in caps:
                data["locations"] = caps["locations"]
            if "items" in caps:
                data["items"] = caps["items"]
            if "goals" in caps:
                data["goals"] = caps["goals"]
            if "item_overrides" in caps:
                data["item_overrides"] = caps["item_overrides"]

        required = ["version", "game", "locations", "items", "checksum"]
        for field in required:
            if field not in data:
                raise ValueError(f"Missing required field: {field}")
        return data

    def _build_option_values(self) -> dict:
        """Build option values dict from all registered options + option_defaults fallback.

        Pass 1: Reads all options from self.options (includes both static ClassVar options
        and any dynamic mod options registered by _register_dynamic_options() at import time).
        Values are native Python types: Toggle → int 0/1, TextChoice → str, Range → int.

        Pass 2: Fallback to option_defaults from capabilities_data for any options not in
        self.options (e.g., _register_dynamic_options() skipped due to missing Players dir,
        or a new option was added to the manifest after the APWorld was last imported).
        """
        option_values: dict = {}

        # Pass 1 — all registered options (static + dynamic)
        for attr_name in dir(self.options):
            if attr_name.startswith("_"):
                continue
            opt = getattr(self.options, attr_name, None)
            if hasattr(opt, "value"):
                option_values[attr_name] = opt.value  # native type

        # Pass 2 — fallback to manifest defaults for unregistered options
        for key, defn in self.capabilities.get("option_defaults", {}).items():
            if key not in option_values:
                typ = defn.get("type", "toggle")
                raw = defn.get("default", "")
                if typ == "toggle":
                    option_values[key] = 1 if str(raw).lower() in ("true", "1", "yes") else 0
                elif typ == "range":
                    try:
                        option_values[key] = int(raw)
                    except (ValueError, TypeError):
                        option_values[key] = 0
                else:  # text_choice
                    option_values[key] = str(raw)

        return option_values

    def _resolve_item_amounts(self, option_values: dict) -> None:
        """Evaluate amount expressions for all items in item_table.

        Items with a non-empty count_expr have their count resolved to an integer
        by evaluate_count(). location_count is len(self.location_table) so that
        {key}% expressions compute correctly against the current in-logic pool size.

        Multiple items may use "fill" (count == -1). create_items() distributes
        remaining pool slots by random draw across all fill candidates.
        """
        location_count = len(self.location_table)

        for name, data in list(self.item_table.items()):
            if not data.count_expr:
                continue  # No expression — count is already correct (including -1 for fill)

            resolved = evaluate_count(data.count_expr, option_values, location_count)
            self.item_table[name] = data._replace(count=resolved)

    def _filter_by_logic(self) -> None:
        """Filter capabilities entries whose logic evaluates to always-False.

        Removes locations, regions, items, and item_overrides from
        self.capabilities whose logic simplifies to False given the player's
        current option values. Prevents creating locations/items/overrides with
        never-satisfiable conditions.
        """
        option_values = self._build_option_values()

        removed_count = 0

        def _keep(entry: dict, kind: str) -> bool:
            nonlocal removed_count
            logic = entry.get("logic", "")
            if is_always_false(logic, option_values):
                self.log.debug(
                    f"Removed always-false {kind} '{entry.get('name', '?')}': {logic}",
                    "Filter",
                )
                removed_count += 1
                return False
            return True

        self.capabilities["locations"] = [
            e for e in self.capabilities.get("locations", [])
            if _keep(e, "location")]
        if "regions" in self.capabilities:
            self.capabilities["regions"] = [
                e for e in self.capabilities.get("regions", [])
                if _keep(e, "region")]
        self.capabilities["items"] = [
            e for e in self.capabilities.get("items", [])
            if _keep(e, "item")]
        if "item_overrides" in self.capabilities:
            self.capabilities["item_overrides"] = [
                e for e in self.capabilities.get("item_overrides", [])
                if _keep(e, "item_override")]
        if removed_count:
            self.log.info(
                f"logic filter: removed {removed_count} always-false entries",
                "Filter",
            )

    def _apply_item_overrides(self) -> None:
        """Apply cross-mod item type overrides.

        When Mod B declares an item_override targeting Mod A's item, the target
        item's type is changed if the override's logic condition is met.
        """
        overrides = self.capabilities.get("item_overrides", [])
        if not overrides:
            return

        option_values = self._build_option_values()

        for ovr in overrides:
            target_item = ovr.get("target_item", "")
            target_mod = ovr.get("target_mod", "")
            new_type = ovr.get("type", "")
            logic = ovr.get("logic", "")

            if not target_item or not new_type:
                continue

            # Check if logic condition is satisfied (option-only logic)
            if logic and is_always_false(logic, option_values):
                self.log.debug(
                    f"Override skipped: '{target_item}' (logic not met: {logic})",
                    "Override",
                )
                continue  # Condition not met — skip this override

            # Find and modify the target item in capabilities
            found = False
            for item in self.capabilities.get("items", []):
                name_match = item.get("name", "") == target_item
                mod_match = not target_mod or item.get("mod_id", "") == target_mod
                if name_match and mod_match:
                    old_type = item.get("type", "?")
                    item["type"] = new_type
                    found = True
                    self.log.info(
                        f"Item override: '{target_item}' {old_type} -> {new_type} "
                        f"(by {ovr.get('source_mod', 'unknown')})",
                        "Override",
                    )

            if not found:
                source = ovr.get("source_mod", "unknown")
                target_desc = f"'{target_item}'"
                if target_mod:
                    target_desc += f" (mod: {target_mod})"
                self.log.error(
                    f"Item override failed: {target_desc} not found in capabilities "
                    f"(declared by {source}). Check target_item/target_mod spelling.",
                    "Override",
                )

    def _build_region_table(self) -> Dict[str, str]:
        """Build region table from capabilities regions data.

        Returns:
            Dict mapping region name to logic expression string.
            Logic is already OR-merged by the C++ capabilities config
            when multiple mods contribute to the same region.
        """
        region_table: Dict[str, str] = {}

        for region_data in self.capabilities.get("regions", []):
            name = region_data["name"]
            logic = region_data.get("logic", "")
            region_table[name] = logic

        return region_table

    def _update_data_package(self) -> None:
        """Update reverse mappings and network data package.

        Archipelago builds the network data package at module import time from
        class-level item_name_to_id and location_name_to_id. Since this world
        populates those dynamically in generate_early(), we must update the
        pre-built data package to reflect the actual mappings.
        """
        # Update reverse mappings (used by Archipelago internals)
        self.__class__.item_id_to_name = {
            code: name for name, code in self.__class__.item_name_to_id.items()
        }
        self.__class__.location_id_to_name = {
            code: name for name, code in self.__class__.location_name_to_id.items()
        }

        # Rebuild and replace the pre-built network data package entry
        import worlds
        worlds.network_data_package["games"][self.game] = self.__class__.get_data_package_data()

        dp = worlds.network_data_package["games"][self.game]
        self.log.debug(
            f"Data package updated: {len(dp.get('item_name_to_id', {}))} items, "
            f"{len(dp.get('location_name_to_id', {}))} locations, "
            f"checksum={dp.get('checksum', 'N/A')}",
            "DataPackage",
        )

    def _build_canonical_ids(self) -> None:
        """Build canonical union ID mapping across all APF players in this multiworld.

        Runs exactly once per multiworld generation (guarded by _canonical_built).
        Decodes each APF player's capabilities_data from their YAML options and builds
        a unified name→ID mapping with unique IDs for every item and location:

          - Same name, same ID across players  → one canonical entry, no remap
          - Same name, different IDs           → use first-seen ID as canonical;
                                                 later players get a remap entry
          - Different names, same ID (collision)→ assign a new free ID to the
                                                 colliding name; player gets a remap

        After this runs, class-level item_name_to_id / location_name_to_id contain
        the full union of all players' items/locations. The data package updated via
        _update_data_package() will include every canonical ID.

        Each player's id_remapping (in slot_data) covers only IDs that differ from
        their raw capabilities IDs. Players with the same mods get empty remaps.
        """
        cls = type(self)

        # Reset if this is a new multiworld generation (handles sequential runs in
        # the same Python process, e.g. tournament / batch generation).
        if cls._canonical_multiworld_seed != self.multiworld.seed:
            cls._canonical_built = False
            cls._canonical_multiworld_seed = self.multiworld.seed
            cls._canonical_player_remaps = {}
            cls.item_name_to_id = {}
            cls.location_name_to_id = {}

        if cls._canonical_built:
            return

        item_name_to_canonical: Dict[str, int] = {}    # name  → canonical_id
        item_id_to_name: Dict[int, str] = {}            # canonical_id → name
        loc_name_to_canonical: Dict[str, int] = {}     # display_name → canonical_id
        loc_id_to_name: Dict[int, str] = {}             # canonical_id → display_name
        all_seen_ids: Set[int] = set()
        next_free: int = 0  # lazy-initialized to max(all_seen_ids)+1

        def find_free_id() -> int:
            nonlocal next_free
            if next_free == 0:
                next_free = (max(all_seen_ids) + 1) if all_seen_ids else 1
            while next_free in all_seen_ids:
                next_free += 1
            result = next_free
            next_free += 1
            all_seen_ids.add(result)
            return result

        per_player_remaps: Dict[int, Dict[int, int]] = {}

        for world in sorted(self.multiworld.worlds.values(), key=lambda w: w.player):
            if not isinstance(world, cls):
                continue

            try:
                raw_cap = world.options.capabilities_data.value
                if not raw_cap:
                    per_player_remaps[world.player] = {}
                    continue
                caps = world._process_capabilities(
                    json.loads(base64.b64decode(raw_cap).decode("utf-8"))
                )
            except Exception as e:
                self.log.warn(
                    f"_build_canonical_ids: could not decode caps for player "
                    f"{world.player}: {e}",
                    "CanonicalIDs",
                )
                per_player_remaps[world.player] = {}
                continue

            player_remap: Dict[int, int] = {}

            # ── Items ─────────────────────────────────────────────────────────
            for item in caps.get("items", []):
                raw_id: int = item["id"]
                name: str = item["name"]
                all_seen_ids.add(raw_id)

                if name in item_name_to_canonical:
                    canonical_id = item_name_to_canonical[name]
                    if raw_id != canonical_id:
                        player_remap[raw_id] = canonical_id
                elif raw_id in item_id_to_name:
                    # True collision: same ID, different name
                    new_id = find_free_id()
                    item_name_to_canonical[name] = new_id
                    item_id_to_name[new_id] = name
                    player_remap[raw_id] = new_id
                else:
                    item_name_to_canonical[name] = raw_id
                    item_id_to_name[raw_id] = name

            # ── Locations ─────────────────────────────────────────────────────
            # Two-pass: first count instances per base name (mirrors build_location_table)
            loc_name_counts: Dict[str, int] = {}
            for loc in caps.get("locations", []):
                loc_name_counts[loc["name"]] = loc_name_counts.get(loc["name"], 0) + 1

            for loc in caps.get("locations", []):
                raw_id = loc["id"]
                base_name: str = loc["name"]
                instance: int = loc.get("instance", 1)
                display_name = (
                    f"{base_name} #{instance}" if loc_name_counts[base_name] > 1 else base_name
                )
                all_seen_ids.add(raw_id)

                if display_name in loc_name_to_canonical:
                    canonical_id = loc_name_to_canonical[display_name]
                    if raw_id != canonical_id:
                        player_remap[raw_id] = canonical_id
                elif raw_id in loc_id_to_name:
                    new_id = find_free_id()
                    loc_name_to_canonical[display_name] = new_id
                    loc_id_to_name[new_id] = display_name
                    player_remap[raw_id] = new_id
                else:
                    loc_name_to_canonical[display_name] = raw_id
                    loc_id_to_name[raw_id] = display_name

            per_player_remaps[world.player] = player_remap

        # Commit canonical mappings to class vars
        cls.item_name_to_id = item_name_to_canonical
        cls.location_name_to_id = loc_name_to_canonical
        cls._canonical_player_remaps = per_player_remaps
        cls._canonical_built = True

        total_remapped = sum(len(r) for r in per_player_remaps.values())
        self.log.info(
            f"Canonical ID union built: {len(item_name_to_canonical)} items, "
            f"{len(loc_name_to_canonical)} locations across "
            f"{len(per_player_remaps)} APF player(s). "
            f"{total_remapped} total ID remap(s) assigned.",
            "CanonicalIDs",
        )

        # Update data package immediately so the full union is visible to Archipelago.
        self._update_data_package()

    def _apply_player_offset(self) -> None:
        """Assign unique IDs per player slot by adding a per-player offset.

        Player 1: base IDs unchanged (e.g. Key A = 6942079)
        Player 2: base + 50,000  (e.g. Key A = 6992079)
        Player 3: base + 100,000, etc.

        Stores forward remap (local→AP) in self.id_remapping for slot_data.
        Player 1 skips this (identity mapping, no slot_data overhead).
        """
        if self.player <= 1:
            return  # Player 1 uses base IDs unchanged

        offset = (self.player - 1) * PER_PLAYER_RANGE
        remap: Dict[int, int] = {}

        new_items: Dict[str, Any] = {}
        for name, data in self.item_table.items():
            new_id = data.code + offset
            remap[data.code] = new_id
            new_items[name] = data._replace(code=new_id)
        self.item_table = new_items

        new_locs: Dict[str, Any] = {}
        for name, data in self.location_table.items():
            new_id = data.code + offset
            remap[data.code] = new_id
            new_locs[name] = data._replace(code=new_id)
        self.location_table = new_locs

        self.id_remapping = remap
        self.__class__.item_name_to_id = {n: d.code for n, d in self.item_table.items()}
        self.__class__.location_name_to_id = {n: d.code for n, d in self.location_table.items()}
        self._update_data_package()

        self.log.info(
            f"Player {self.player}: applied ID offset +{offset} "
            f"({len(remap)} IDs remapped)",
            "IDOffset",
        )

    def check_id_conflicts(self) -> None:
        """Check for ID conflicts with other worlds and remap if necessary."""
        # Collect all IDs used by other worlds
        used_ids: Set[int] = set()

        for world in self.multiworld.worlds.values():
            if world.player == self.player:
                continue

            # Skip other APF worlds: all APF-APF conflicts were already resolved by
            # _build_canonical_ids(). Checking them here would cause false positives
            # because all APF instances share the same class-level item_name_to_id
            # (which now contains the full canonical union).
            if isinstance(world, type(self)):
                continue

            # Get location IDs
            for loc in world.multiworld.get_locations(world.player):
                if loc.address is not None:
                    used_ids.add(loc.address)

            # Get item IDs
            for item_name, item_id in getattr(world, "item_name_to_id", {}).items():
                if item_id is not None:
                    used_ids.add(item_id)

        # Check for conflicts
        my_location_ids = {data.code for data in self.location_table.values()}
        my_item_ids = {data.code for data in self.item_table.values()}
        my_ids = my_location_ids | my_item_ids

        conflicts = my_ids & used_ids

        if conflicts:
            self.remap_ids(conflicts, used_ids)

    def remap_ids(self, conflicting_ids: Set[int], all_used_ids: Set[int]) -> None:
        """Remap conflicting IDs to safe values."""
        # Find safe starting point
        all_my_ids = {data.code for data in self.item_table.values()}
        all_my_ids |= {data.code for data in self.location_table.values()}
        all_ids = all_used_ids | all_my_ids

        safe_start = max(all_ids) + 1000 if all_ids else self.capabilities.get("id_base", 6942067) + 100000

        # Build remapping
        remap: Dict[int, int] = {}
        for old_id in sorted(conflicting_ids):
            remap[old_id] = safe_start
            safe_start += 1

        # Compose with the existing id_remapping (set by _apply_player_offset, if any).
        # The prior remap maps { base_id → offset_id }; remap maps { offset_id → safe_id }.
        # C++ only knows base IDs, so id_remapping must ultimately map base_id → final_ap_id.
        prior = self.id_remapping  # {} for player 1, {base→offset} for player 2+
        if prior:
            # Update entries in the prior remap whose offset_id was conflicted.
            # Entries whose offset_id was not conflicted keep their offset value unchanged.
            composed: Dict[int, int] = {
                base_id: remap.get(ap_id, ap_id) for base_id, ap_id in prior.items()
            }
            self.id_remapping = composed
        else:
            # No prior offset (player 1): conflict remap maps base_id → safe_id directly.
            self.id_remapping = remap

        # Apply remapping to location table (preserve all fields)
        new_location_table = {}
        for name, data in self.location_table.items():
            new_code = remap.get(data.code, data.code)
            new_location_table[name] = LocationData(
                code=new_code,
                name=data.name,
                mod_id=data.mod_id,
                region=data.region,
                logic=data.logic,
            )
        self.location_table = new_location_table

        # Apply remapping to item table (preserve all fields)
        new_item_table = {}
        for name, data in self.item_table.items():
            new_code = remap.get(data.code, data.code)
            new_item_table[name] = ItemData(
                code=new_code,
                name=data.name,
                classification=data.classification,
                mod_id=data.mod_id,
                count=data.count,
                logic=data.logic,
            )
        self.item_table = new_item_table

        # Merge remapped entries into class-level mappings.
        # Use update (not replace) so the canonical union built by _build_canonical_ids()
        # is preserved — only the entries remapped for this player are overwritten.
        for name, data in self.item_table.items():
            self.__class__.item_name_to_id[name] = data.code
        for name, data in self.location_table.items():
            self.__class__.location_name_to_id[name] = data.code

        # Refresh data package with remapped IDs
        self._update_data_package()

        self.log.warn(
            f"ID conflict resolved: {len(conflicting_ids)} IDs remapped to safe range "
            f"starting at {next(iter(remap.values())) if remap else '?'}. "
            f"id_remapping now covers {len(self.id_remapping)} entries.",
            "IDConflict",
        )

    def create_regions(self) -> None:
        """Create regions and locations.

        When logic_mode is "basic" and regions are defined, creates proper regions
        with Menu connecting to all of them. Locations are placed into their
        designated regions. Locations without a declared region go into "Main".

        When logic_mode is "none" or no regions exist, all locations go into a
        single "Main" region (flat Sphere 0 behavior).
        """
        menu_region = Region("Menu", self.player, self.multiworld)
        self.multiworld.regions.append(menu_region)

        use_regions = (self.options.logic_mode.value == 1 and self.region_table)

        # Build region objects — always create "Main" as the default region
        regions: Dict[str, Region] = {}
        regions["Main"] = Region("Main", self.player, self.multiworld)

        if use_regions:
            for region_name in self.region_table:
                if region_name not in regions:
                    regions[region_name] = Region(region_name, self.player, self.multiworld)

        # Place locations into their target regions
        for loc_name, loc_data in self.location_table.items():
            target_region = loc_data.region if use_regions else "Main"

            # If the target region wasn't declared, create it on-the-fly
            if target_region not in regions:
                regions[target_region] = Region(target_region, self.player, self.multiworld)

            region = regions[target_region]
            location = APFrameworkLocation(
                self.player,
                loc_name,
                loc_data.code,
                region
            )
            region.locations.append(location)

        # Connect Menu to all regions (flat topology — item requirements enforce ordering)
        for region in regions.values():
            menu_region.connect(region)
            self.multiworld.regions.append(region)

        loc_count = sum(len(r.locations) for r in regions.values())
        self.log.info(
            f"Created {len(regions)} regions with {loc_count} locations",
            "Regions",
        )

    def create_item(self, name: str) -> APFrameworkItem:
        """Create an item by name. Required by Archipelago for pre-fill and similar."""
        item_data = self.item_table.get(name)
        if item_data:
            return APFrameworkItem(name, item_data.classification, item_data.code, self.player)
        return APFrameworkItem(name, ItemClassification.filler,
                               self.item_name_to_id.get(name, 0), self.player)

    def create_items(self) -> None:
        """Create items and add to item pool.

        Balances the pool so len(itempool) == len(locations):
        - Over-budget: culls lowest-priority items (trap < filler < useful).
          Never culls progression — that indicates a manifest bug.
        - Under-budget: fills remaining slots with filler/trap items.
        """
        import random

        total_locations = len(self.location_table)

        # --- Count phase ---
        # Separate fixed items (count >= 1) from filler templates (count == -1)
        fixed_items: list[tuple[str, ItemData]] = []
        filler_item_names: list[str] = []

        for item_name, item_data in self.item_table.items():
            if item_data.count == -1:
                filler_item_names.append(item_name)
            else:
                for _ in range(item_data.count):
                    fixed_items.append((item_name, item_data))

        fixed_count = len(fixed_items)
        self.log.debug(
            f"Pool budget: {fixed_count} fixed items, "
            f"{len(filler_item_names)} filler templates, "
            f"{total_locations} locations",
            "Items",
        )

        # --- Over-budget cull ---
        if fixed_count > total_locations:
            excess = fixed_count - total_locations
            self.log.warn(
                f"Over-budget by {excess}: {fixed_count} fixed items > "
                f"{total_locations} locations — culling lowest priority",
                "Items",
            )

            # Priority: trap(0) < filler(1) < useful(2) < progression(3)
            _PRIORITY = {
                ItemClassification.trap: 0,
                ItemClassification.filler: 1,
                ItemClassification.useful: 2,
                ItemClassification.progression: 3,
            }

            # Sort: lowest priority first; within same priority, highest index
            # first so we cull duplicates before unique entries
            fixed_items.sort(
                key=lambda pair: (_PRIORITY.get(pair[1].classification, 1), -pair[1].count),
            )

            culled = 0
            remaining_items: list[tuple[str, ItemData]] = []
            for name, data in fixed_items:
                if culled < excess and _PRIORITY.get(data.classification, 1) < 3:
                    self.log.warn(f"Culled item: '{name}' ({data.classification.name})", "Items")
                    culled += 1
                else:
                    remaining_items.append((name, data))

            if culled < excess:
                raise Exception(
                    f"[{self.game}] Cannot balance item pool: {excess} excess items "
                    f"but only {culled} non-progression items available to cull. "
                    f"This is a manifest configuration error."
                )

            fixed_items = remaining_items

        # --- Create fixed items ---
        prog_count = 0
        useful_count = 0
        filler_count = 0
        trap_count = 0

        for item_name, item_data in fixed_items:
            item = APFrameworkItem(
                item_name, item_data.classification, item_data.code, self.player
            )
            self.multiworld.itempool.append(item)
            if item_data.classification == ItemClassification.progression:
                prog_count += 1
            elif item_data.classification == ItemClassification.useful:
                useful_count += 1
            elif item_data.classification == ItemClassification.trap:
                trap_count += 1
            else:
                filler_count += 1

        # --- Under-budget fill ---
        remaining = total_locations - len(fixed_items)
        if remaining > 0 and filler_item_names:
            trap_chance = self.options.trap_item_chance.value / 100.0
            trap_items = get_trap_items(self.item_table)

            for _ in range(remaining):
                if trap_items and random.random() < trap_chance:
                    item_name = random.choice(trap_items)
                else:
                    item_name = random.choice(filler_item_names)

                item_data = self.item_table[item_name]
                item = APFrameworkItem(
                    item_name, item_data.classification, item_data.code, self.player
                )
                self.multiworld.itempool.append(item)
                if item_data.classification == ItemClassification.trap:
                    trap_count += 1
                else:
                    filler_count += 1

        # --- Log composition ---
        total_created = prog_count + useful_count + filler_count + trap_count
        self.log.info(
            f"Item pool: {prog_count} progression, {useful_count} useful, "
            f"{filler_count} filler, {trap_count} trap = {total_created} total "
            f"for {total_locations} locations",
            "Items",
        )

        assert total_created == total_locations, (
            f"Item pool size mismatch: {total_created} items != {total_locations} locations"
        )

    def set_rules(self) -> None:
        """Set access rules for locations."""
        set_rules(self)
        set_completion_rules(self)

    def fill_slot_data(self) -> Dict[str, Any]:
        """Return data to be sent to the client.

        Includes option_values so the C++ tracker engine can evaluate
        (Option: ...) logic expressions at runtime with the player's
        actual chosen YAML options.
        """
        if getattr(self, "_is_stub", False):
            raise RuntimeError(
                "[APFramework] fill_slot_data() called in stub mode — "
                "this indicates a missing capabilities_data in the player YAML. "
                "Use the YAML generated by the APF Manager."
            )
        slot_data: Dict[str, Any] = {
            "id_remapping":     self.id_remapping,
            "id_reverse_remap": {v: k for k, v in self.id_remapping.items()},
        }

        # Serialize option values for C++ logic evaluation (all values as strings)
        options_dict: Dict[str, str] = {
            k: str(v) for k, v in self._build_option_values().items()
        }
        slot_data["option_values"] = options_dict

        self.log.debug(
            f"fill_slot_data: player={self.player}, "
            f"{len(self.id_remapping)} ID remaps, "
            f"{len(options_dict)} options, "
            f"{len(self.__class__.item_name_to_id)} items, "
            f"{len(self.__class__.location_name_to_id)} locations",
            "SlotData",
        )
        return slot_data

    def get_filler_item_name(self) -> str:
        """Get a random filler item name."""
        filler_items = get_filler_items(self.item_table)
        if filler_items:
            import random
            return random.choice(filler_items)
        # Fallback - return first item
        if self.item_table:
            return next(iter(self.item_table.keys()))
        return "Nothing"


